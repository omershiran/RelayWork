"""Exercise the local demo deployment and verify its isolated payment journal."""

import subprocess
from datetime import UTC, datetime, timedelta
from uuid import uuid4

import httpx

ORIGIN = "http://127.0.0.1:8093"
MAIL = "/var/lib/agentrelai-demo/mail"
PASSWORD = "Local sandbox verification " + uuid4().hex


def signup(client):
    email = f"sandbox-check-{uuid4().hex}@example.com"
    payload = {"email": email, "password": PASSWORD}
    client.post("/auth/register", json=payload).raise_for_status()
    emails = subprocess.check_output(
        ["sudo", "-u", "agentrelai_demo", "find", MAIL, "-type", "f", "-exec", "cat", "{}", "+"],
        text=True,
    )
    token = emails.split(f"To: {email}\n", 1)[1].split("#verify:", 1)[1].splitlines()[0]
    client.post("/auth/verify", json={"token": token, "password": PASSWORD}).raise_for_status()
    client.post("/auth/login", json=payload).raise_for_status()


def verified_order(buyer, supplier):
    stamp = datetime.now(UTC)
    expires = (stamp + timedelta(days=2)).isoformat()
    due = (stamp + timedelta(days=4)).isoformat()
    work = buyer.post("/work-requests", json={
        "title": "Sandbox verification listing",
        "category": "sandbox-verification",
        "description": "Generated by the sandbox verification script.",
        "deliverable": "Sandbox verification result",
        "due_at": due, "expires_at": expires,
    }).raise_for_status().json()
    thread = supplier.post("/conversations", json={
        "client_id": str(uuid4()), "kind": "work", "resource_id": work["id"], "body": "Sandbox reply",
    }).raise_for_status().json()
    path = "/conversations/" + thread["id"]
    quote = supplier.post(path + "/quotes", json={
        "client_id": str(uuid4()), "price_cents": 1799, "description": "Sandbox verification",
        "deliverables": "Sandbox delivery", "terms": "Sandbox terms", "due_at": due, "expires_at": expires,
    }).raise_for_status().json()
    buyer.post(path + "/quotes/" + quote["id"] + "/accept", json={
        "confirmed_price_cents": 1799
    }).raise_for_status()
    return path


def run():
    with (
        httpx.Client(base_url=ORIGIN + "/api/v1", headers={"Origin": ORIGIN}) as buyer,
        httpx.Client(base_url=ORIGIN + "/api/v1", headers={"Origin": ORIGIN}) as supplier,
    ):
        signup(buyer)
        signup(supplier)
        thread = verified_order(buyer, supplier)
        payment_path = thread + "/payment"
        checkout = thread + "/sandbox-checkout"
        assert supplier.post(payment_path).status_code == 403
        pending = buyer.post(payment_path).raise_for_status().json()
        assert buyer.post(payment_path).raise_for_status().json() == pending
        assert pending["status"] == "AWAITING_CHECKOUT" and pending["amount_cents"] == 1799
        forged = buyer.post("/payments/sandbox/callback", json={"payment_id": pending["id"]},
                            headers={"x-agentrelai-signature": "forged"})
        assert forged.status_code == 401
        assert buyer.get(payment_path).json() == pending
        confirmed = buyer.post(checkout).raise_for_status().json()
        assert confirmed["status"] == "SANDBOX_CONFIRMED"
        assert buyer.post(checkout).raise_for_status().json() == confirmed
        assert supplier.get(payment_path).raise_for_status().json() == confirmed
        assert supplier.get(thread + "/order").raise_for_status().json()["payment_status"] == "SANDBOX_CONFIRMED"

    query = """
        select count(*), sum(l.signed_cents) from financial_ledger l
        join payment_events e on l.event_id = e.id
        where e.payment_id = :'payment_id'::uuid;
    """
    ledger = subprocess.check_output(
        ["sudo", "-u", "agentrelai_demo", "psql", "-At", "-d", "agentrelai_demo",
         "-v", f"payment_id={confirmed['id']}", "-v", "ON_ERROR_STOP=1"],
        input=query, text=True,
    )
    assert ledger.strip() == "2|0"
    response = httpx.post("https://agentrelai.com/api/v1/payments/sandbox/callback", json={})
    assert response.status_code == 503
    print("Sandbox checkout, forged callback rejection, replay and balanced ledger verified. Public callback disabled.")


if __name__ == "__main__":
    run()
